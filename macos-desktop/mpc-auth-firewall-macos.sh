#!/usr/bin/env bash
# macOS host packet filter for an MPA Wallet node on Docker Desktop.
#
# Docker Desktop accepts forwarded ports on the Mac before the packet enters
# the Linux VM, where every internet address usually looks like the Docker
# gateway. These rules stay on the router-facing interface (pf), which still
# sees the real source. utun, WireGuard, ipsec, and other VPN interfaces are
# not selected as that interface, so VPN traffic is not capped.
#
# Caps and the scanner allowlist come from scripts/lib/mpc-auth-ddos-guard.sh
# --print-plan. Only new SYNs are limited. Existing states are kept. There is
# no flush and no permanent ban table.
#
# Usage:
#   mpc-auth-firewall-macos.sh --install
#   mpc-auth-firewall-macos.sh                  # apply (launchd)
#   mpc-auth-firewall-macos.sh --remove
#   mpc-auth-firewall-macos.sh --print-anchor --interface en0 --config configs.yaml

set -euo pipefail

MACOS_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GUARD="${MACOS_ROOT}/../scripts/lib/mpc-auth-ddos-guard.sh"
LABEL="com.continuumdao.mpc-auth-firewall"
ANCHOR_NAME="continuum-mpc"
ANCHOR_FILE="/etc/pf.anchors/${ANCHOR_NAME}"
PF_CONF="/etc/pf.conf"
MARKER_BEGIN="# BEGIN continuum-mpc-anchor"
MARKER_END="# END continuum-mpc-anchor"
PLIST_DST="/Library/LaunchDaemons/${LABEL}.plist"

MODE="apply"
CONFIG=""
INTERFACE=""

usage() {
	echo "usage: $0 [--install|--remove|--print-anchor] [--config configs.yaml] [--interface en0]" >&2
}

while [[ $# -gt 0 ]]; do
	case "$1" in
	--install) MODE="install"; shift ;;
	--remove) MODE="remove"; shift ;;
	--print-anchor) MODE="print"; shift ;;
	--config)
		CONFIG="${2:-}"
		shift 2
		;;
	--interface)
		INTERFACE="${2:-}"
		shift 2
		;;
	-h | --help) usage; exit 0 ;;
	*) usage; exit 1 ;;
	esac
done

repo_dir() {
	if [[ -f "${MACOS_ROOT}/repo-dir.txt" ]]; then
		cat "${MACOS_ROOT}/repo-dir.txt"
		return 0
	fi
	cd "${MACOS_ROOT}/.." && pwd
}

if [[ -z "$CONFIG" ]]; then
	if [[ -n "${MPC_AUTH_COMPOSE_WORKDIR:-}" && -f "${MPC_AUTH_COMPOSE_WORKDIR}/configs.yaml" ]]; then
		CONFIG="${MPC_AUTH_COMPOSE_WORKDIR}/configs.yaml"
	else
		CONFIG="$(repo_dir)/configs.yaml"
	fi
fi

pf_rate() {
	local rate="$1"
	case "$rate" in
	*/sec) printf '%s/1\n' "${rate%/sec}" ;;
	*/minute) printf '%s/60\n' "${rate%/minute}" ;;
	*)
		echo "mpc-auth-firewall-macos: unsupported rate ${rate}" >&2
		return 1
		;;
	esac
}

pick_interface() {
	if [[ -n "$INTERFACE" ]]; then
		printf '%s\n' "$INTERFACE"
		return 0
	fi
	local def=""
	if command -v route >/dev/null 2>&1; then
		def="$(route -n get default 2>/dev/null | awk '/interface:/{print $2; exit}')"
	fi
	case "$def" in
	"" | utun* | wg* | ipsec* | ppp* | tun* | tap* | gif* | stf*) def="" ;;
	esac
	if [[ -n "$def" ]]; then
		printf '%s\n' "$def"
		return 0
	fi
	local iface
	if command -v ifconfig >/dev/null 2>&1; then
		while read -r iface; do
			case "$iface" in
			en*)
				printf '%s\n' "$iface"
				return 0
				;;
			esac
		done < <(ifconfig -l 2>/dev/null | tr ' ' '\n')
	fi
	echo "mpc-auth-firewall-macos: no router-facing interface (default route is a VPN or missing)" >&2
	return 1
}

render_anchor() {
	local iface="$1"
	local plan="$2"
	local line port above rate burst src pf
	local -a scan_v4=() scan_v6=()
	local scan_port="" scan_above="" scan_rate=""

	if [[ ! "$iface" =~ ^[A-Za-z0-9]+$ ]]; then
		echo "mpc-auth-firewall-macos: refusing interface name ${iface}" >&2
		return 1
	fi

	printf '%s\n' "# Generated by mpc-auth-firewall-macos.sh. Re-run after configs.yaml changes."
	printf '%s\n' "# New SYNs on ${iface} only. VPN interfaces are not this interface."

	while IFS= read -r line || [[ -n "$line" ]]; do
		[[ -z "$line" ]] && continue
		case "$line" in
		CAP=*)
			# CAP=<port> <connlimit-above> <rate> <burst>
			read -r port above rate burst <<<"${line#CAP=}"
			pf="$(pf_rate "$rate")"
			printf 'pass in quick on %s inet proto tcp from any to any port %s flags S/SA keep state (max-src-conn %s, max-src-conn-rate %s)\n' \
				"$iface" "$port" "$above" "$pf"
			printf 'block in quick on %s inet proto tcp from any to any port %s flags S/SA\n' "$iface" "$port"
			printf 'pass in quick on %s inet6 proto tcp from any to any port %s flags S/SA keep state (max-src-conn %s, max-src-conn-rate %s)\n' \
				"$iface" "$port" "$above" "$pf"
			printf 'block in quick on %s inet6 proto tcp from any to any port %s flags S/SA\n' "$iface" "$port"
			;;
		SCANCAP=*)
			read -r scan_port scan_above scan_rate burst src <<<"${line#SCANCAP=}"
			if [[ "$src" == *:* ]]; then
				scan_v6+=("$src")
			else
				scan_v4+=("$src")
			fi
			;;
		SCANDROP=*)
			;;
		SSH=*)
			# SSH=<port> <connlimit-above> <rate> <burst>
			read -r port above rate burst <<<"${line#SSH=}"
			pf="$(pf_rate "$rate")"
			printf 'pass in quick on %s inet proto tcp from any to any port %s flags S/SA keep state (max-src-conn %s, max-src-conn-rate %s)\n' \
				"$iface" "$port" "$above" "$pf"
			printf 'block in quick on %s inet proto tcp from any to any port %s flags S/SA\n' "$iface" "$port"
			printf 'pass in quick on %s inet6 proto tcp from any to any port %s flags S/SA keep state (max-src-conn %s, max-src-conn-rate %s)\n' \
				"$iface" "$port" "$above" "$pf"
			printf 'block in quick on %s inet6 proto tcp from any to any port %s flags S/SA\n' "$iface" "$port"
			;;
		WAN=* | IGNORE=*) ;;
		*)
			echo "mpc-auth-firewall-macos: bad plan line: ${line}" >&2
			return 1
			;;
		esac
	done <<<"$plan"

	if [[ -n "$scan_port" ]]; then
		pf="$(pf_rate "$scan_rate")"
		if [[ ${#scan_v4[@]} -gt 0 ]]; then
			local joined=""
			local item
			for item in "${scan_v4[@]}"; do
				if [[ -n "$joined" ]]; then
					joined+=", "
				fi
				joined+="$item"
			done
			printf 'pass in quick on %s inet proto tcp from { %s } to any port %s flags S/SA keep state (max-src-conn %s, max-src-conn-rate %s)\n' \
				"$iface" "$joined" "$scan_port" "$scan_above" "$pf"
		fi
		printf 'block in quick on %s inet proto tcp from any to any port %s flags S/SA\n' "$iface" "$scan_port"
		if [[ ${#scan_v6[@]} -gt 0 ]]; then
			local joined6=""
			local item6
			for item6 in "${scan_v6[@]}"; do
				if [[ -n "$joined6" ]]; then
					joined6+=", "
				fi
				joined6+="$item6"
			done
			printf 'pass in quick on %s inet6 proto tcp from { %s } to any port %s flags S/SA keep state (max-src-conn %s, max-src-conn-rate %s)\n' \
				"$iface" "$joined6" "$scan_port" "$scan_above" "$pf"
		fi
		printf 'block in quick on %s inet6 proto tcp from any to any port %s flags S/SA\n' "$iface" "$scan_port"
	fi
}

prepare_python() {
	local repo
	repo="$(repo_dir)"
	if [[ -x "${repo}/.venv-provision/bin/python3" ]]; then
		export PATH="${repo}/.venv-provision/bin:${PATH}"
	fi
	if [[ -d "${repo}/.provision-py" ]]; then
		export PYTHONPATH="${repo}/.provision-py${PYTHONPATH:+:${PYTHONPATH}}"
	fi
}

load_plan() {
	if [[ ! -f "$CONFIG" ]]; then
		echo "mpc-auth-firewall-macos: configs.yaml not found at ${CONFIG}" >&2
		return 1
	fi
	if [[ ! -x "$GUARD" && ! -f "$GUARD" ]]; then
		echo "mpc-auth-firewall-macos: missing ${GUARD}" >&2
		return 1
	fi
	prepare_python
	"$GUARD" --config "$CONFIG" --print-plan
}

ensure_root() {
	if [[ "${EUID:-$(id -u)}" -eq 0 ]]; then
		return 0
	fi
	if ! sudo -n true 2>/dev/null; then
		echo "mpc-auth-firewall-macos: passwordless sudo is required to load the pf anchor" >&2
		return 1
	fi
	exec sudo -n -- "$0" "$@"
}

install_launchdaemon() {
	local repo template
	repo="$(repo_dir)"
	template="${MACOS_ROOT}/com.continuumdao.mpc-auth-firewall.plist"
	if [[ ! -f "$template" ]]; then
		echo "mpc-auth-firewall-macos: missing ${template}" >&2
		return 1
	fi
	sed -e "s|__MACOS_DESKTOP_ROOT__|${MACOS_ROOT}|g" -e "s|__REPO_DIR__|${repo}|g" "$template" >"$PLIST_DST"
	chmod 0644 "$PLIST_DST"
	launchctl bootout "system/${LABEL}" 2>/dev/null || launchctl unload "$PLIST_DST" 2>/dev/null || true
	launchctl bootstrap system "$PLIST_DST" 2>/dev/null || launchctl load -w "$PLIST_DST"
	echo "Loaded LaunchDaemon ${LABEL}"
}

apply_anchor() {
	local iface plan tmp edited=0
	iface="$(pick_interface)"
	plan="$(load_plan)"
	tmp="$(mktemp)"
	render_anchor "$iface" "$plan" >"$tmp"
	mkdir -p /etc/pf.anchors
	if ! pfctl -nf "$tmp"; then
		rm -f "$tmp"
		echo "mpc-auth-firewall-macos: pf rejected the anchor" >&2
		return 1
	fi
	install -m 0644 "$tmp" "$ANCHOR_FILE"
	rm -f "$tmp"
	if [[ ! -f "$PF_CONF" ]]; then
		echo "mpc-auth-firewall-macos: ${PF_CONF} is missing" >&2
		return 1
	fi
	if ! grep -q -F "$MARKER_BEGIN" "$PF_CONF"; then
		if [[ ! -f "${PF_CONF}.continuum-mpc.bak" ]]; then
			cp "$PF_CONF" "${PF_CONF}.continuum-mpc.bak"
		fi
		cat >>"$PF_CONF" <<EOF

${MARKER_BEGIN}
anchor "${ANCHOR_NAME}"
load anchor "${ANCHOR_NAME}" from "${ANCHOR_FILE}"
${MARKER_END}
EOF
		edited=1
		if ! pfctl -nf "$PF_CONF"; then
			if [[ -f "${PF_CONF}.continuum-mpc.bak" ]]; then
				cp "${PF_CONF}.continuum-mpc.bak" "$PF_CONF"
			fi
			echo "mpc-auth-firewall-macos: pf rejected ${PF_CONF}; restored backup" >&2
			return 1
		fi
		pfctl -f "$PF_CONF"
	else
		pfctl -a "$ANCHOR_NAME" -f "$ANCHOR_FILE"
	fi
	if ! pfctl -s info 2>/dev/null | grep -q "Status: Enabled"; then
		pfctl -e || true
	fi
	echo "mpc-auth-firewall-macos: caps loaded on ${iface}"
	if [[ "$edited" -eq 1 ]]; then
		echo "mpc-auth-firewall-macos: referenced ${ANCHOR_NAME} from ${PF_CONF}"
	fi
}

remove_anchor() {
	launchctl bootout "system/${LABEL}" 2>/dev/null || true
	if [[ -f "$PLIST_DST" ]]; then
		launchctl unload "$PLIST_DST" 2>/dev/null || true
		rm -f "$PLIST_DST"
	fi
	rm -f "$ANCHOR_FILE"
	if [[ -f "$PF_CONF" ]] && grep -q -F "$MARKER_BEGIN" "$PF_CONF"; then
		tmp="$(mktemp)"
		awk -v begin="$MARKER_BEGIN" -v end="$MARKER_END" '
			$0 == begin { skip = 1; next }
			$0 == end { skip = 0; next }
			skip != 1 { print }
		' "$PF_CONF" >"$tmp"
		mv "$tmp" "$PF_CONF"
		if pfctl -nf "$PF_CONF"; then
			pfctl -f "$PF_CONF" || true
		fi
	fi
	echo "mpc-auth-firewall-macos: removed ${LABEL}"
}

case "$MODE" in
print)
	iface="$(pick_interface)"
	plan="$(load_plan)"
	render_anchor "$iface" "$plan"
	;;
remove)
	ensure_root "$@"
	remove_anchor
	;;
install)
	ensure_root "$@"
	apply_anchor
	install_launchdaemon
	;;
apply)
	ensure_root "$@"
	apply_anchor
	;;
*)
	usage
	exit 1
	;;
esac
